def list_topics() -> list[TopicMeta]:
    return TOPICS


def get_topic_meta(topic_id: str) -> TopicMeta | None:
    for topic in TOPICS:
        if topic.topic_id == topic_id:
            return topic
    return None


def get_topic_display(topic: TopicMeta, lang: str = DEFAULT_LANGUAGE) -> tuple[str, str]:
    """Возвращает (category, title) на выбранном языке через строковый
    каталог; если ключа нет ни на запрошенном, ни на резервном языке —
    откатывается на русские значения из самого TopicMeta (никогда не
    показывает пользователю технический ключ вида "[[topic.x.title]]")."""
    lang = normalize_language(lang)
    category = t(f"topic.{topic.topic_id}.category", lang)
    title = t(f"topic.{topic.topic_id}.title", lang)
    if category.startswith("[["):
        category = topic.category
    if title.startswith("[["):
        title = topic.title
    return category, title


def load_topic_content(topic_id: str, lang: str = DEFAULT_LANGUAGE) -> list[dict]:
    """
    Загружает содержимое темы из data/theory/<topic_id>.<lang>.json.
    Если перевода на запрошенный язык нет — откатывается на
    DEFAULT_LANGUAGE ("ru"). Возвращает пустой список, если тема совсем
    не наполнена ни на одном языке (ещё в разработке).
    """
    lang = normalize_language(lang)
    path = DATA_DIR / f"{topic_id}.{lang}.json"
    if not path.exists() and lang != DEFAULT_LANGUAGE:
        path = DATA_DIR / f"{topic_id}.{DEFAULT_LANGUAGE}.json"
    if not path.exists():
        return []
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    # Новый формат (МППСС с официальным текстом, 2026-10): {"meta": ..., "entries": [...]}.
    # Старый формат — просто список записей. Наружу всегда отдаём список.
    if isinstance(data, dict):
        return data.get("entries", [])
    return data


def load_topic_meta(topic_id: str, lang: str = DEFAULT_LANGUAGE) -> dict:
    """Метаданные темы (источник официального текста, список исправленных
    опечаток источника) — только для тем в новом формате {"meta", "entries"}."""
    lang = normalize_language(lang)
    path = DATA_DIR / f"{topic_id}.{lang}.json"
    if not path.exists() and lang != DEFAULT_LANGUAGE:
        path = DATA_DIR / f"{topic_id}.{DEFAULT_LANGUAGE}.json"
    if not path.exists():
        return {}
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    return data.get("meta", {}) if isinstance(data, dict) else {}


