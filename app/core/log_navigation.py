"""
Счисление пути по показаниям лага — классическая штурманская задача
"Определение пройденного расстояния и поправки лага" (курс
"Судовождение").

Термины (стандартная практика, MT/учебники навигации):
  ОЛ  — отсчёт лага (показание счётчика лага в момент замера), мили лага.
  РОЛ — разность отсчётов лага между двумя моментами: РОЛ = ОЛ2 - ОЛ1.
  Кл  — коэффициент лага: множитель, переводящий РОЛ в пройденное
        расстояние S = РОЛ × Кл. У исправного лага Кл близок к 1
        (обычно 0.95-1.05).
  ΔЛ% — поправка лага в процентах: тот же множитель, выраженный как
        отклонение от 100% — S = РОЛ × (1 + ΔЛ%/100).
        Соотношение с коэффициентом: Кл = 1 + ΔЛ%/100.

Оба представления (Кл и ΔЛ%) математически эквивалентны — это просто
два общепринятых способа записи одного и того же множителя; конвертация
между ними — kl_to_percent()/percent_to_kl().

Коэффициент/поправка лага определяются практически на мерной линии
(мерном галсе/базе) — сравнением показания лага (РОЛ) с точно известным
пройденным расстоянием (Sфакт), измеренным другим способом (например,
по объектам с известными координатами): Кл = Sфакт / РОЛ.

Источник: стандартная штурманская практика (учебники "Судовождение"),
не требует ссылки на конкретный нормативный документ — сама формула не
регламентируется, а вытекает из определения коэффициента лага.

Единицы: расстояние/ОЛ/РОЛ — мили лага (числ. совпадают с милями после
умножения на Кл), Кл — безразмерный множитель, ΔЛ% — проценты.
"""

from dataclasses import dataclass, field


@dataclass
class CalculationStep:
    description: str
    formula: str
    substitution: str
    result: str


@dataclass
class LogResult:
    value: float
    steps: list[CalculationStep] = field(default_factory=list)


def kl_to_percent(kl: float) -> float:
    """Коэффициент лага -> поправка лага в процентах: ΔЛ% = (Кл - 1) × 100."""
    return (kl - 1.0) * 100.0


def percent_to_kl(delta_l_percent: float) -> float:
    """Поправка лага в процентах -> коэффициент лага: Кл = 1 + ΔЛ%/100."""
    return 1.0 + delta_l_percent / 100.0


def distance_by_log(rol: float, kl: float) -> LogResult:
    """
    Пройденное судном расстояние по показаниям лага: S = РОЛ × Кл.

    rol (РОЛ) — разность отсчётов лага (ОЛ2 - ОЛ1), мили лага
    kl (Кл) — коэффициент лага
    """
    distance = rol * kl
    steps = [
        CalculationStep(
            description="Пройденное расстояние по лагу",
            formula="S = РОЛ × Кл",
            substitution=f"S = {rol:.2f} × {kl:.4f}",
            result=f"S = {distance:.2f} мили",
        )
    ]
    return LogResult(value=distance, steps=steps)


def log_coefficient_from_distance(actual_distance_nm: float, rol: float) -> LogResult:
    """
    Определение коэффициента лага по известному (фактическому) пройденному
    расстоянию (например, на мерной линии/по контрольным объектам) и
    разности отсчётов лага за тот же промежуток: Кл = Sфакт / РОЛ.

    actual_distance_nm (Sфакт) — фактически пройденное расстояние, мили
    rol (РОЛ) — разность отсчётов лага за тот же промежуток, мили лага
    """
    if rol == 0:
        raise ValueError("err.log.rol_zero")
    kl = actual_distance_nm / rol
    steps = [
        CalculationStep(
            description="Коэффициент лага",
            formula="Кл = Sфакт / РОЛ",
            substitution=f"Кл = {actual_distance_nm:.2f} / {rol:.2f}",
            result=f"Кл = {kl:.4f}  (ΔЛ% = {kl_to_percent(kl):+.2f}%)",
        )
    ]
    return LogResult(value=kl, steps=steps)
