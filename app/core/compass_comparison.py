"""
Сличение показаний двух компасов (например, путевой/главный магнитный
компас и гирокомпас, или основной и запасной гирокомпас) — рутинная
проверка, которую вахтенный помощник выполняет регулярно (обычно
каждую вахту), чтобы вовремя заметить неисправность или увеличившуюся
погрешность одного из приборов.

Считает только разницу двух одновременно снятых показаний, приведённую
к кратчайшему угловому расхождению (от -180° до +180° — например,
разница между 359° и 002° это +3°, а не -357°). Само число ничего не
"решает" за вахтенного помощника: конкретный порог допустимого
расхождения (когда пора докладывать/подстраивать/чинить компас) в
источниках не унифицирован — задаётся паспортом прибора и СУБ судна,
здесь не утверждается как факт (правило 4 CLAUDE.md).

Источник: сама операция (сличение показаний компасов) — общепринятая
рутинная штурманская практика (упоминается во многих учебниках
судовождения и в конкурентных приложениях как отдельный инструмент);
конкретной формулы в конвенциях/кодексах ИМО нет — это просто разница
курсовых углов, приведённая к кратчайшему расхождению.

Единицы: все углы — градусы, 0-360°.
"""

from dataclasses import dataclass, field


@dataclass
class CalculationStep:
    description: str
    formula: str
    substitution: str
    result: str


@dataclass
class CompassComparisonResult:
    difference: float  # -180..+180, "+" — компас B показывает больше компаса A
    steps: list[CalculationStep] = field(default_factory=list)


def compass_comparison(heading_a: float, heading_b: float) -> CompassComparisonResult:
    """
    heading_a, heading_b — одновременно снятые показания двух компасов,
        ° (0-360, любое значение будет нормализовано)

    Возвращает разницу (heading_b - heading_a), приведённую к
    кратчайшему угловому расхождению в диапазоне (-180, +180].
    Положительное значение — компас B показывает БОЛЬШИЙ курс, чем A.
    """
    raw_diff = (heading_b - heading_a) % 360.0
    if raw_diff > 180.0:
        raw_diff -= 360.0

    steps = [
        CalculationStep(
            description="Разница показаний, приведённая к кратчайшему расхождению",
            formula="Δ = ((B − A + 180°) mod 360°) − 180°",
            substitution=f"Δ = ((({heading_b:.1f} − {heading_a:.1f}) mod 360°) приведено к ±180°)",
            result=f"Δ = {raw_diff:+.1f}°",
        )
    ]
    return CompassComparisonResult(difference=raw_diff, steps=steps)
